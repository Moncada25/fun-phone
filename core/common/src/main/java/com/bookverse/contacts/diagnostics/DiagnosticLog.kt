internal enum class DiagnosticLevel {
    DEBUG,
    WARNING,
    ERROR,
}

internal fun interface DiagnosticSink {
    fun record(level: DiagnosticLevel, event: DiagnosticEvent)
}

internal class DiagnosticLogger(
    private val sink: DiagnosticSink,
) {
    fun debug(event: DiagnosticEvent) = sink.record(DiagnosticLevel.DEBUG, event)

    fun warning(event: DiagnosticEvent) = sink.record(DiagnosticLevel.WARNING, event)

    fun error(event: DiagnosticEvent) = sink.record(DiagnosticLevel.ERROR, event)
}

private object LogcatDiagnosticSink : DiagnosticSink {
    private const val TAG = "FunPhone"

    override fun record(level: DiagnosticLevel, event: DiagnosticEvent) {
        val priority = when (level) {
            DiagnosticLevel.DEBUG -> Log.DEBUG
            DiagnosticLevel.WARNING -> Log.WARN
            DiagnosticLevel.ERROR -> Log.ERROR
        }
        Log.println(priority, TAG, event.name)
    }
}

internal object NoOpDiagnosticSink : DiagnosticSink {
    override fun record(level: DiagnosticLevel, event: DiagnosticEvent) = Unit
}

internal fun defaultDiagnosticSink(isDebugBuild: Boolean): DiagnosticSink =
    if (isDebugBuild) LogcatDiagnosticSink else NoOpDiagnosticSink

/** Central diagnostics facade. Release builds intentionally discard every event. */
object DiagnosticLog {
    private val logger = DiagnosticLogger(
        sink = defaultDiagnosticSink(BuildConfig.DEBUG),
    )

    fun debug(event: DiagnosticEvent) = logger.debug(event)

    fun warning(event: DiagnosticEvent) = logger.warning(event)

    fun error(event: DiagnosticEvent) = logger.error(event)
}
